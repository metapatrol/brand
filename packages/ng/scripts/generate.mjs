// Generates src/lib/generated/ before every build and test:
//
//   icons.ts  the built-in icons, from Lucide (https://lucide.dev, ISC license,
//             Copyright (c) Lucide Icons and Contributors) — markup inlined, so
//             applications need no icon package
//   marks.ts  the mark in its three optical sizes, from @metapatrol/brand, with
//             the colours replaced by the classes mp-mark-structure and
//             mp-mark-signal, which @metapatrol/style colours per theme
//
// Both fail loudly on anything unexpected rather than ship a wrong icon or a
// mark in the wrong colours.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const lucide = require("lucide");
const out = new URL("../src/lib/generated/", import.meta.url);
mkdirSync(out, { recursive: true });

/** The icons the components use, plus the few every console needs. */
const ICONS = [
  "chevron-left",
  "chevron-right",
  "chevron-down",
  "panel-left-close",
  "panel-left-open",
  "menu",
  "x",
  "sun",
  "moon",
  "copy",
  "check",
  "log-out",
  "log-in",
  "eye",
  "eye-off",
  "info",
  "external-link",
  "search",
];

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const attr = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;");

const icons = ICONS.map((name) => {
  const node = lucide[pascal(name)];
  if (!Array.isArray(node)) throw new Error(`lucide has no icon "${name}" (${pascal(name)})`);
  const markup = node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${attr(v)}"`).join(" ")}/>`)
    .join("");
  return `  '${name}': '${markup}',`;
});

writeFileSync(
  new URL("icons.ts", out),
  `// generated by scripts/generate.mjs from lucide ${require("lucide/package.json").version}, do not edit
// Lucide, ISC license, Copyright (c) Lucide Icons and Contributors

/** Inner markup of 24×24 stroke icons. */
export const BUILT_IN_ICONS = {
${icons.join("\n")}
} as const;

export type BuiltInIconName = keyof typeof BUILT_IN_ICONS;
`,
);

const brand = dirname(require.resolve("@metapatrol/brand/package.json"));
const STRUCTURE = /<g fill="#[0-9A-Fa-f]{6}">/;
const SIGNAL = /<path fill="#[0-9A-Fa-f]{6}" d=/;

const marks = Object.entries({
  primary: "metapatrol-mark-dark.svg",
  small: "metapatrol-mark-small-dark.svg",
  favicon: "metapatrol-mark-favicon-dark.svg",
}).map(([size, file]) => {
  const svg = readFileSync(join(brand, "mark", file), "utf8").trim();
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  if (!viewBox || !STRUCTURE.test(inner) || !SIGNAL.test(inner)) {
    throw new Error(`${file} does not have the expected structure (one <g fill>, one signal <path fill>)`);
  }
  const body = inner
    .replace(STRUCTURE, '<g class="mp-mark-structure">')
    .replace(SIGNAL, '<path class="mp-mark-signal" d=');
  if (/fill="#/.test(body)) throw new Error(`${file}: a fixed colour is left after replacing`);
  return `  ${size}: { viewBox: '${viewBox}', body: '${body}' },`;
});

writeFileSync(
  new URL("marks.ts", out),
  `// generated by scripts/generate.mjs from @metapatrol/brand ${require("@metapatrol/brand/package.json").version}, do not edit

/** The mark's optical sizes: favicon up to 16 px, small up to 40 px, primary above. */
export const MARKS = {
${marks.join("\n")}
} as const;

export type MarkSize = keyof typeof MARKS;
`,
);

console.log(`generated ${ICONS.length} icons and ${marks.length} mark sizes`);
