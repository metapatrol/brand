// Assembles dist/: the hand-written CSS and SCSS, the token SCSS from
// @metapatrol/tokens, and the Tailwind theme generated from the tokens.
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { theme, tokenName } from "@metapatrol/tokens";

const require = createRequire(import.meta.url);
const dist = new URL("../dist/", import.meta.url);
const src = new URL("../src/", import.meta.url);
const scss = new URL("../scss/", import.meta.url);

rmSync(dist, { recursive: true, force: true });
mkdirSync(new URL("scss/", dist), { recursive: true });
for (const f of readdirSync(src)) copyFileSync(new URL(f, src), new URL(f, dist));
for (const f of readdirSync(scss)) copyFileSync(new URL(f, scss), new URL(`scss/${f}`, dist));
copyFileSync(require.resolve("@metapatrol/tokens/tokens.scss"), new URL("scss/_tokens.scss", dist));

const dark = theme("dark");
const keys = Object.keys(dark);
const roles = keys.filter((k) => k.startsWith("color.") && !/^color\.(neutral|cyan|green|amber|red|blue)\./.test(k));
const sizes = keys.filter((k) => k.startsWith("font.size."));
const radii = keys.filter((k) => k.startsWith("radius."));

const lines = [
  "/* generated by @metapatrol/style from @metapatrol/tokens, do not edit */",
  "",
  "/* inline: utilities reference the --mp-* variables directly, so a nested",
  "   [data-theme] container switches every utility inside it. */",
  "@theme inline {",
  "  /* only the semantic roles: bg-surface, text-fg-muted, border-line-strong, ... */",
  "  --color-*: initial;",
  ...roles.map((k) => `  --color-${tokenName(k)}: var(--mp-${tokenName(k)});`),
  "",
  "  --font-sans: var(--mp-font-family-sans);",
  "  --font-mono: var(--mp-font-family-mono);",
  "",
  "  /* dense UI scale: text-base is 14px, text-md 16px for reading text */",
  ...sizes.map((k) => `  --text-${k.slice("font.size.".length)}: var(--mp-${tokenName(k)});`),
  "  --text-md--line-height: 1.5;",
  "",
  ...radii.map((k) => `  --radius-${k.slice("radius.".length)}: var(--mp-${tokenName(k)});`),
  "}",
  "",
  "/* dark: and light: follow the same rule as the tokens: an explicit",
  "   data-theme wins, otherwise the system preference, otherwise dark. */",
  "@custom-variant dark {",
  '  &:where([data-theme="dark"], [data-theme="dark"] *) {',
  "    @slot;",
  "  }",
  "  @media not (prefers-color-scheme: light) {",
  '    &:where(:root:not([data-theme="light"]), :root:not([data-theme="light"]) *) {',
  "      @slot;",
  "    }",
  "  }",
  "}",
  "@custom-variant light {",
  '  &:where([data-theme="light"], [data-theme="light"] *) {',
  "    @slot;",
  "  }",
  "  @media (prefers-color-scheme: light) {",
  '    &:where(:root:not([data-theme="dark"]), :root:not([data-theme="dark"]) *) {',
  "      @slot;",
  "    }",
  "  }",
  "}",
  "",
];
writeFileSync(new URL("tailwind-theme.css", dist), lines.join("\n"));
console.log(`dist: ${roles.length} colour roles, ${sizes.length} sizes, ${radii.length} radii`);
